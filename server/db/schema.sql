-- Схема БД сервиса заявок в снабжение (PostgreSQL 14+).
-- Скрипт идемпотентный: его можно запускать повторно (npm run db:migrate).

CREATE TABLE IF NOT EXISTS departments (
  id   SERIAL PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS categories (
  id   SERIAL PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS users (
  id            SERIAL PRIMARY KEY,
  full_name     TEXT NOT NULL CHECK (length(btrim(full_name)) > 0),
  email         TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'employee'
                CHECK (role IN ('employee', 'buyer', 'admin')),
  department_id INTEGER REFERENCES departments(id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS requests (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  author_id     INTEGER NOT NULL REFERENCES users(id),
  category_id   INTEGER NOT NULL REFERENCES categories(id),
  is_urgent     BOOLEAN NOT NULL DEFAULT false,
  due_date      DATE,
  budget        NUMERIC(14, 2) CHECK (budget IS NULL OR budget >= 0),
  justification TEXT NOT NULL CHECK (length(btrim(justification)) > 0),
  status        TEXT NOT NULL DEFAULT 'new'
                CHECK (status IN ('new', 'review', 'buying', 'done', 'rejected', 'cancelled')),
  buyer_comment TEXT NOT NULL DEFAULT '',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS request_items (
  id         SERIAL PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  name       TEXT NOT NULL CHECK (length(btrim(name)) > 0),
  quantity   INTEGER NOT NULL CHECK (quantity > 0),
  unit       TEXT NOT NULL DEFAULT 'шт.'
);

CREATE TABLE IF NOT EXISTS status_history (
  id         SERIAL PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  old_status TEXT,
  new_status TEXT NOT NULL,
  changed_by INTEGER NOT NULL REFERENCES users(id),
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_requests_author  ON requests(author_id);
CREATE INDEX IF NOT EXISTS idx_requests_status  ON requests(status);
CREATE INDEX IF NOT EXISTS idx_items_request    ON request_items(request_id);
CREATE INDEX IF NOT EXISTS idx_history_request  ON status_history(request_id);
